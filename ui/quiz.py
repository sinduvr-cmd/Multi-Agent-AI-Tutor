"""
UI Module: Interactive Quiz Generator and One-Question-at-a-Time Quiz Engine.
Features:
- Practice Mode (instant feedback, hints, why right/wrong explanation, step-by-step math, source page)
- Exam Mode (timed, hidden answers, Section A-E blueprint, final report)
- State persistence preventing duplicate marks on Streamlit reruns
- All CBSE question types: MCQ, Fill Blank, Numerical, True/False, Assertion-Reason, Short, Long, Matching, Case Study.
"""

import uuid
from datetime import datetime
from typing import Dict, Any, List, Optional
import streamlit as st
import database.db as db
from orchestration.tutor_flow import TutorFlow
from services.grading_service import GradingService


def render_quiz_view(flow: TutorFlow, active_student_id: str):
    # Check if an active quiz session is already in progress
    if "current_quiz" in st.session_state and st.session_state["current_quiz"]:
        render_active_quiz(flow, active_student_id)
    else:
        render_quiz_generator(flow, active_student_id)


def render_quiz_generator(flow: TutorFlow, active_student_id: str):
    st.markdown("""
    <div class="tutor-hero-card">
        <div class="tutor-hero-title">📝 Interactive Quiz Generator</div>
        <div class="tutor-hero-subtitle">
            Configure an adaptive quiz or full CBSE examination paper. 
            All questions are generated by Agent 3 and verified by Agent 4 (QA Specialist).
        </div>
    </div>
    """, unsafe_allow_html=True)

    documents = db.list_documents()
    if not documents:
        st.warning("No chapters uploaded yet. Please upload a chapter or load a sample from 'Upload Chapter'.")
        return

    doc_options = {d["document_id"]: f"{d['title']} ({d['grade']})" for d in documents}
    selected_doc_id = st.selectbox(
        "Select Chapter:",
        options=list(doc_options.keys()),
        format_func=lambda x: doc_options[x],
        index=0 if "selected_document_id" not in st.session_state or st.session_state["selected_document_id"] not in doc_options else list(doc_options.keys()).index(st.session_state["selected_document_id"])
    )
    st.session_state["selected_document_id"] = selected_doc_id

    topics = db.get_document_topics(selected_doc_id)
    topic_options = ["All Topics"] + [t["title"] for t in topics]
    selected_topic = st.selectbox("Select Topic:", options=topic_options)

    # Configuration Controls
    col_c1, col_c2, col_c3 = st.columns(3)
    with col_c1:
        question_count = st.selectbox("Number of Questions:", options=[5, 10, 15, 20, 25, 30], index=0)
    with col_c2:
        difficulty = st.selectbox("Difficulty Level:", options=["Mixed", "Easy", "Medium", "Hard"], index=0)
    with col_c3:
        quiz_mode = st.radio("Quiz Mode:", options=["Practice Mode", "Exam Mode"], horizontal=True)

    # Question Types Selection
    all_qtypes = [
        "MCQ", "Fill Blank", "Numerical", "True/False", 
        "Assertion and Reason", "Short Answer", "Long Answer", 
        "Case Study", "Matching"
    ]
    selected_qtypes = st.multiselect(
        "Allowed Question Formats:",
        options=all_qtypes,
        default=["MCQ", "Fill Blank", "Numerical", "True/False", "Assertion and Reason"]
    )

    if not selected_qtypes:
        st.error("Please select at least one question type.")
        return

    st.write("")
    if st.button("🚀 Generate Validated Quiz with Multi-Agent Crew", type="primary", use_container_width=True):
        with st.spinner("Agent 3 (Question Setter) is crafting questions and Agent 4 (QA Specialist) is auditing with SymPy..."):
            filter_topic = selected_topic if selected_topic != "All Topics" else "All"
            questions = flow.generate_and_validate_quiz(
                document_id=selected_doc_id,
                topic=filter_topic,
                count=question_count,
                difficulty=difficulty,
                question_types=selected_qtypes
            )

            if not questions:
                st.error("Failed to generate questions. Falling back to pre-verified question bank...")
                questions = flow.question_generator._get_fallback_questions(
                    selected_doc_id, "Perimeter and Area", filter_topic, question_count, difficulty, selected_qtypes, [1, 2]
                )

            # Guarantee all questions are saved in database
            if questions:
                db.save_questions(questions)

            # Initialize Quiz Session
            sess_id = f"sess_{uuid.uuid4().hex[:8]}"
            total_marks = sum(q.get("marks", 1) for q in questions)
            
            session_state = {
                "session_id": sess_id,
                "student_id": active_student_id,
                "document_id": selected_doc_id,
                "chapter_title": db.get_document(selected_doc_id)["title"],
                "mode": quiz_mode,
                "total_marks": total_marks,
                "current_index": 0,
                "questions": questions,
                "answers": {},
                "evaluations": {},
                "locked_attempts": {},
                "flagged_questions": [],
                "is_completed": False,
                "start_time": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            }
            
            # Save to database
            db.save_quiz_session(session_state)
            
            # Store in session state
            st.session_state["current_quiz"] = session_state
            st.rerun()


def render_active_quiz(flow: TutorFlow, active_student_id: str):
    quiz = st.session_state["current_quiz"]
    questions = quiz["questions"]
    curr_idx = quiz["current_index"]
    total_q = len(questions)

    # Check if quiz completed
    if quiz.get("is_completed", False):
        render_quiz_results(quiz)
        return

    q = questions[curr_idx]
    q_id = q["question_id"]
    is_practice = (quiz["mode"] == "Practice Mode")
    is_locked = bool(quiz["locked_attempts"].get(q_id, False))

    # Top Header & Progress Bar
    st.markdown(f"### 📝 {quiz['chapter_title']} ({quiz['mode']})")
    progress_val = (curr_idx + 1) / total_q
    st.progress(progress_val)

    # Info Bar: Question #, Marks, Topic, Difficulty, Flag
    col_info1, col_info2 = st.columns([3, 1])
    with col_info1:
        diff_class = f"badge-{q.get('difficulty', 'medium').lower()}"
        st.markdown(f"""
        <b>Question {curr_idx + 1} of {total_q}</b> &nbsp;|&nbsp; 
        <span class="badge-pill {diff_class}">{q.get('difficulty', 'Medium')}</span> &nbsp;
        <span class="badge-pill badge-topic">{q.get('topic', 'General')}</span> &nbsp;
        <span class="badge-pill badge-marks">{q.get('marks', 1)} Mark(s)</span>
        """, unsafe_allow_html=True)
    with col_info2:
        is_flagged = q_id in quiz["flagged_questions"]
        flag_btn_label = "🚩 Flagged" if is_flagged else "🏳️ Flag for Review"
        if st.button(flag_btn_label, key=f"btn_flag_{q_id}"):
            if is_flagged:
                quiz["flagged_questions"].remove(q_id)
            else:
                quiz["flagged_questions"].append(q_id)
            st.rerun()

    st.write("")

    # Question Box
    st.markdown(f"""
    <div class="quiz-question-box">
        <div class="quiz-question-text">{q['question_text']}</div>
    </div>
    """, unsafe_allow_html=True)

    # Diagram if present
    if q.get("diagram_reference"):
        st.image(q["diagram_reference"], caption="Problem Figure / Reference Diagram", width=350)

    # Input Control by Question Type (NO PRESELECTION!)
    q_type = q.get("question_type", "MCQ")
    existing_ans = quiz["answers"].get(q_id, None)

    student_selection = None

    if q_type in ["MCQ", "Assertion and Reason"]:
        options = q.get("options") or []
        # Find index if previously submitted
        idx = options.index(existing_ans) if existing_ans in options else None
        student_selection = st.radio(
            "Select your answer:",
            options=options,
            index=idx,
            disabled=is_locked,
            key=f"input_{q_id}"
        )

    elif q_type == "True/False":
        tf_options = ["True", "False"]
        idx = tf_options.index(existing_ans) if existing_ans in tf_options else None
        student_selection = st.radio(
            "Select True or False:",
            options=tf_options,
            index=idx,
            disabled=is_locked,
            key=f"input_{q_id}"
        )

    elif q_type in ["Fill Blank", "Numerical"]:
        val = existing_ans if existing_ans else ""
        student_selection = st.text_input(
            "Enter your numerical/text answer (e.g. 50 or 50 cm):",
            value=val,
            disabled=is_locked,
            key=f"input_{q_id}"
        )

    elif q_type in ["Short Answer", "Long Answer"]:
        val = existing_ans if existing_ans else ""
        student_selection = st.text_area(
            "Write your step-by-step answer:",
            value=val,
            disabled=is_locked,
            key=f"input_{q_id}",
            height=120
        )

    elif q_type == "Matching":
        pairs = q.get("matching_pairs", {})
        st.write("Match each item on the left with its definition:")
        student_mappings = {}
        for k, v in pairs.items():
            opts = list(pairs.values())
            m_sel = st.selectbox(f"**{k}** maps to:", options=opts, key=f"match_{q_id}_{k}", disabled=is_locked)
            student_mappings[k] = m_sel
        student_selection = str(student_mappings)

    else:  # Case Study / Diagram fallback
        val = existing_ans if existing_ans else ""
        student_selection = st.text_area("Your response:", value=val, disabled=is_locked, key=f"input_{q_id}")

    # Auto-save student selection to answer memory
    if student_selection is not None and str(student_selection).strip() != "":
        quiz["answers"][q_id] = str(student_selection).strip()

    st.write("")

    # Action Buttons: Submit Answer, Hint, Navigation
    col_act1, col_act2, col_act3, col_act4, col_act5 = st.columns([1.5, 1, 1, 1, 1.5])

    # 1. Submit Answer
    with col_act1:
        if not is_locked:
            if st.button("✅ Submit Answer", type="primary", use_container_width=True, key=f"btn_sub_{q_id}"):
                if not student_selection or str(student_selection).strip() == "":
                    st.warning("Please choose or enter an answer before submitting.")
                else:
                    ans_str = str(student_selection).strip()
                    quiz["answers"][q_id] = ans_str
                    eval_res = flow.evaluate_student_answer(
                        session_id=quiz["session_id"],
                        student_id=active_student_id,
                        question=q,
                        student_answer=ans_str
                    )
                    quiz["evaluations"][q_id] = eval_res
                    quiz["locked_attempts"][q_id] = True
                    quiz["current_score"] = sum(ev["marks_awarded"] for ev in quiz["evaluations"].values())
                    db.save_quiz_session(quiz)
                    st.rerun()
        else:
            st.success("Attempt Locked ✓")

    # 2. Hint Button (Practice Mode only)
    with col_act2:
        if is_practice:
            if st.button("💡 Hint", use_container_width=True, key=f"btn_hint_{q_id}"):
                st.info(f"Hint: Look at formulas on Page(s) {q.get('source_pages', [1])}. {q.get('solution_steps', [''])[0]}")

    # 3. Previous Question
    with col_act3:
        if curr_idx > 0:
            if st.button("⬅️ Previous", use_container_width=True, key="btn_prev"):
                if student_selection:
                    quiz["answers"][q_id] = str(student_selection).strip()
                quiz["current_index"] -= 1
                db.save_quiz_session(quiz)
                st.rerun()

    # 4. Next Question
    with col_act4:
        if curr_idx < total_q - 1:
            if st.button("Next ➡️", use_container_width=True, key="btn_next"):
                if student_selection:
                    ans_str = str(student_selection).strip()
                    quiz["answers"][q_id] = ans_str
                    # In practice mode, auto-evaluate if answer given but not yet locked
                    if is_practice and not is_locked and ans_str:
                        eval_res = flow.evaluate_student_answer(
                            session_id=quiz["session_id"],
                            student_id=active_student_id,
                            question=q,
                            student_answer=ans_str
                        )
                        quiz["evaluations"][q_id] = eval_res
                        quiz["locked_attempts"][q_id] = True
                        quiz["current_score"] = sum(ev["marks_awarded"] for ev in quiz["evaluations"].values())
                quiz["current_index"] += 1
                db.save_quiz_session(quiz)
                st.rerun()

    # 5. Finish / Submit Quiz
    with col_act5:
        if st.button("🏁 Finish Quiz", use_container_width=True, key="btn_finish"):
            if student_selection:
                quiz["answers"][q_id] = str(student_selection).strip()
            
            # Grade ALL questions in the quiz (unanswered ones receive 0 marks)
            for q_item in questions:
                item_id = q_item["question_id"]
                if item_id not in quiz["evaluations"]:
                    ans = quiz["answers"].get(item_id, "")
                    eval_res = flow.evaluate_student_answer(
                        session_id=quiz["session_id"],
                        student_id=active_student_id,
                        question=q_item,
                        student_answer=ans
                    )
                    quiz["evaluations"][item_id] = eval_res
                    quiz["locked_attempts"][item_id] = True

            quiz["is_completed"] = True
            quiz["end_time"] = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            quiz["current_score"] = sum(ev["marks_awarded"] for ev in quiz["evaluations"].values())
            db.save_quiz_session(quiz)
            st.rerun()

    # Practice Mode Immediate Feedback (Displayed only after submission)
    if is_practice and is_locked and q_id in quiz["evaluations"]:
        ev = quiz["evaluations"][q_id]
        if ev["is_correct"]:
            st.markdown(f"""
            <div class="feedback-correct">
                <b>🎉 Correct! (+{ev['marks_awarded']} Marks)</b><br/>
                {ev['feedback']}
            </div>
            """, unsafe_allow_html=True)
        else:
            st.markdown(f"""
            <div class="feedback-incorrect">
                <b>❌ Incorrect (0 Marks)</b><br/>
                {ev['feedback']}
            </div>
            """, unsafe_allow_html=True)

        # Show detailed solution, math steps & source pages
        with st.expander("📖 Step-by-Step Solution & Textbook Grounding", expanded=True):
            st.markdown(f"**Correct Answer:** `{q.get('correct_answer')}`")
            if q.get("solution_steps"):
                st.markdown("**Solution Steps:**")
                for s in q["solution_steps"]:
                    st.markdown(f"1. {s}")
            st.markdown(f"**Explanation:** {q.get('explanation')}")
            st.markdown(f"**Source Reference:** Verified against `{q.get('chapter')}`, Page(s) **{q.get('source_pages', [1])}**")


def render_quiz_results(quiz: Dict[str, Any]):
    st.markdown("""
    <div class="tutor-hero-card">
        <div class="tutor-hero-title">🎉 Quiz Completed!</div>
        <div class="tutor-hero-subtitle">
            Here is your comprehensive assessment performance report and topic breakdown.
        </div>
    </div>
    """, unsafe_allow_html=True)

    questions = quiz["questions"]
    evaluations = quiz.get("evaluations", {})
    total_marks = quiz["total_marks"]
    earned_marks = sum(ev.get("marks_awarded", 0.0) for ev in evaluations.values())
    pct = round((earned_marks / max(1, total_marks)) * 100.0, 1)

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Total Marks", f"{earned_marks:.1f} / {total_marks}")
    c2.metric("Score Percentage", f"{pct}%")
    c3.metric("Questions Answered", f"{len(evaluations)} / {len(questions)}")
    correct_count = sum(1 for ev in evaluations.values() if ev.get("is_correct"))
    c4.metric("Correct Answers", f"{correct_count} / {len(questions)}")

    st.write("")

    # Restart or New Quiz buttons
    col_b1, col_b2 = st.columns(2)
    with col_b1:
        if st.button("🔄 Retake This Quiz", use_container_width=True):
            st.session_state["current_quiz"] = None
            st.rerun()
    with col_b2:
        if st.button("📊 View Progress & Mastery Radar", type="primary", use_container_width=True):
            st.session_state["current_quiz"] = None
            st.session_state["current_view"] = "My Progress"
            st.rerun()

    st.divider()

    st.divider()

    # Segregate Wrong vs Correct Questions
    wrong_questions = []
    correct_questions = []

    for idx, q in enumerate(questions):
        q_id = q["question_id"]
        ev = evaluations.get(q_id)
        is_corr = ev.get("is_correct") if ev else False
        item_data = {"index": idx + 1, "question": q, "evaluation": ev, "is_correct": is_corr}
        if is_corr:
            correct_questions.append(item_data)
        else:
            wrong_questions.append(item_data)

    st.subheader("📋 Comprehensive Question Review")
    st.caption("Inspect your mistakes, compare your answers with the correct solutions, and read step-by-step textbook explanations.")

    tab_wrong, tab_correct, tab_all = st.tabs([
        f"❌ Incorrect Questions ({len(wrong_questions)})",
        f"✅ Correct Questions ({len(correct_questions)})",
        f"📑 All Questions ({len(questions)})"
    ])

    def render_question_review_card(item):
        idx = item["index"]
        q = item["question"]
        ev = item["evaluation"]
        is_corr = item["is_correct"]

        stud_ans = ev.get("student_answer", "").strip() if ev else ""
        if not stud_ans:
            stud_ans = "No Answer (Skipped / Blank)"
        corr_ans = q.get("correct_answer", "")
        max_m = q.get("marks", 1)
        awarded_m = ev.get("marks_awarded", 0.0) if ev else 0.0

        diff_class = f"badge-{q.get('difficulty', 'medium').lower()}"

        if not is_corr:
            st.markdown(f"""
            <div style="background: rgba(30, 41, 59, 0.7); border: 2px solid #EF4444; border-radius: 14px; 
                        padding: 20px 24px; margin-bottom: 20px; box-shadow: 0 4px 16px rgba(239, 68, 68, 0.2);">
                <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 12px;">
                    <span style="font-size: 16px; font-weight: 800; color: #FCA5A5;">❌ Question {idx} &nbsp;—&nbsp; INCORRECT (0.0 / {max_m} Marks)</span>
                    <div>
                        <span class="badge-pill {diff_class}">{q.get('difficulty', 'Medium')}</span>
                        <span class="badge-pill badge-topic">{q.get('topic', 'General')}</span>
                    </div>
                </div>
                <div style="font-size: 16px; font-weight: 600; color: #F8FAFC; margin-bottom: 16px; line-height: 1.5;">
                    {q.get('question_text')}
                </div>
                <div style="display: grid; grid-template-columns: 1fr 1fr; gap: 14px; margin-bottom: 16px;">
                    <div style="background: rgba(127, 29, 29, 0.45); border: 1.5px solid #EF4444; border-radius: 10px; padding: 12px 16px;">
                        <div style="font-size: 12px; font-weight: 700; color: #FCA5A5; text-transform: uppercase;">Your Submitted Answer</div>
                        <div style="font-size: 16px; font-weight: 700; color: #FEE2E2; margin-top: 4px;">{stud_ans}</div>
                    </div>
                    <div style="background: rgba(6, 78, 59, 0.5); border: 1.5px solid #10B981; border-radius: 10px; padding: 12px 16px;">
                        <div style="font-size: 12px; font-weight: 700; color: #6EE7B7; text-transform: uppercase;">Correct Answer</div>
                        <div style="font-size: 16px; font-weight: 700; color: #ECFDF5; margin-top: 4px;">{corr_ans}</div>
                    </div>
                </div>
                <div style="background: rgba(15, 23, 42, 0.85); border-left: 4px solid #38BDF8; border-radius: 8px; padding: 14px 18px;">
                    <div style="font-size: 13px; font-weight: 700; color: #38BDF8; text-transform: uppercase; margin-bottom: 4px;">💡 Step-by-Step Explanation & Why Correct</div>
                    <div style="font-size: 14px; color: #E2E8F0; line-height: 1.6;">{q.get('explanation')}</div>
                    <div style="font-size: 12px; color: #94A3B8; margin-top: 8px;"><b>Source Textbook:</b> {q.get('chapter')}, Page(s) <b>{q.get('source_pages', [1])}</b></div>
                </div>
            </div>
            """, unsafe_allow_html=True)
            
            # Show detailed solution steps if present
            if q.get("solution_steps"):
                with st.expander(f"🔍 Show Detailed Calculation Steps for Q{idx}"):
                    for s_idx, step in enumerate(q["solution_steps"]):
                        st.markdown(f"**Step {s_idx + 1}:** {step}")

        else:
            st.markdown(f"""
            <div style="background: rgba(30, 41, 59, 0.7); border: 2px solid #10B981; border-radius: 14px; 
                        padding: 20px 24px; margin-bottom: 20px; box-shadow: 0 4px 16px rgba(16, 185, 129, 0.2);">
                <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 12px;">
                    <span style="font-size: 16px; font-weight: 800; color: #6EE7B7;">✅ Question {idx} &nbsp;—&nbsp; CORRECT (+{awarded_m:.1f} / {max_m} Marks)</span>
                    <div>
                        <span class="badge-pill {diff_class}">{q.get('difficulty', 'Medium')}</span>
                        <span class="badge-pill badge-topic">{q.get('topic', 'General')}</span>
                    </div>
                </div>
                <div style="font-size: 16px; font-weight: 600; color: #F8FAFC; margin-bottom: 16px; line-height: 1.5;">
                    {q.get('question_text')}
                </div>
                <div style="background: rgba(6, 78, 59, 0.4); border: 1.5px solid #10B981; border-radius: 10px; padding: 12px 16px; margin-bottom: 14px;">
                    <div style="font-size: 12px; font-weight: 700; color: #6EE7B7; text-transform: uppercase;">Your Correct Answer</div>
                    <div style="font-size: 16px; font-weight: 700; color: #ECFDF5; margin-top: 4px;">{stud_ans}</div>
                </div>
                <div style="background: rgba(15, 23, 42, 0.85); border-left: 4px solid #10B981; border-radius: 8px; padding: 14px 18px;">
                    <div style="font-size: 13px; font-weight: 700; color: #6EE7B7; text-transform: uppercase; margin-bottom: 4px;">💡 Solution & Explanation</div>
                    <div style="font-size: 14px; color: #E2E8F0; line-height: 1.6;">{q.get('explanation')}</div>
                    <div style="font-size: 12px; color: #94A3B8; margin-top: 8px;"><b>Source Textbook:</b> {q.get('chapter')}, Page(s) <b>{q.get('source_pages', [1])}</b></div>
                </div>
            </div>
            """, unsafe_allow_html=True)

    with tab_wrong:
        if wrong_questions:
            st.error(f"You got {len(wrong_questions)} question(s) incorrect. Review each one below to master the concepts!")
            for item in wrong_questions:
                render_question_review_card(item)
        else:
            st.success("🎉 Outstanding! You had 0 incorrect answers in this quiz.")

    with tab_correct:
        if correct_questions:
            st.success(f"Great work! You answered {len(correct_questions)} question(s) correctly.")
            for item in correct_questions:
                render_question_review_card(item)
        else:
            st.warning("No questions were answered correctly in this attempt. Review the solutions in the 'Incorrect Questions' tab!")

    with tab_all:
        for idx, q in enumerate(questions):
            ev = evaluations.get(q["question_id"])
            render_question_review_card({
                "index": idx + 1,
                "question": q,
                "evaluation": ev,
                "is_correct": ev.get("is_correct") if ev else False
            })
